  if (v.phone.replace(/\D/g, '').length !== 12) { er.textContent = tr('Проверьте номер телефона'); return; }
  if (!v.date) { er.textContent = tr('Выберите дату'); return; }
  if (v.date === todayStr() && parseInt(v.time, 10) <= new Date().getHours()) {
    er.textContent = tr('Это время уже прошло — выберите более позднее'); return;
  }
  er.textContent = '';

